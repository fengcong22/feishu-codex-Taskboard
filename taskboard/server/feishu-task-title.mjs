export const TASK_TITLE_MAX_LENGTH = 240;

function shorten(value, limit) {
  if (value.length <= limit) return value;
  // Keep UTF-16 pairs intact while respecting the task API's string length limit.
  let prefix = value.slice(0, Math.max(0, limit - 1));
  if (/[\uD800-\uDBFF]$/.test(prefix)) prefix = prefix.slice(0, -1);
  return `${prefix}…`;
}

function legacyTitle({ tableName, recordId, nameSuffix }) {
  return `${tableName ?? "Auto-Cut"} · ${recordId} · ${nameSuffix}`;
}

export function feishuStageTaskTitle({ tableName, recordId, nameSuffix, namingDisplayValue }) {
  const courseName = typeof namingDisplayValue === "string" ? namingDisplayValue.trim() : "";
  const prefix = `${tableName ?? "Auto-Cut"} · `;
  const suffix = ` · ${nameSuffix}`;
  const available = TASK_TITLE_MAX_LENGTH - prefix.length - suffix.length;
  if (available > 0) return `${prefix}${shorten(courseName || recordId, available)}${suffix}`;
  return shorten(`${prefix}${courseName || recordId}${suffix}`, TASK_TITLE_MAX_LENGTH);
}

export function feishuTaskDisplayTitle(task, origin, subjectVersion) {
  // Only replace the exact title generated by older releases, using the task's
  // captured workflow version. Custom titles and provenance remain untouched.
  if (!subjectVersion || !origin?.stageId || !origin.stageSnapshot
    || typeof origin.controlledContext?.namingDisplayValue !== "string"
    || !origin.controlledContext.namingDisplayValue.trim()) return task.title;
  const input = {
    tableName: subjectVersion.tableName,
    recordId: origin.recordId,
    nameSuffix: origin.stageSnapshot.nameSuffix,
  };
  if (task.title !== legacyTitle(input)) return task.title;
  return feishuStageTaskTitle({ ...input, namingDisplayValue: origin.controlledContext.namingDisplayValue });
}
